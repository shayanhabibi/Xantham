import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { brotliCompressSync, constants, inflateRawSync } from 'node:zlib';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const packageId = 'Fickl.Core.Ts';
const read = file => readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const xml = text => String(text).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
const property = (text, name) => {
  const value = text.match(new RegExp(`<${name}>([^<]+)</${name}>`))?.[1];
  assert.ok(value, `Missing ${name}`);
  return value;
};
const dependency = (text, name) => {
  const value = text.match(new RegExp(`<PackageReference Include="${name.replaceAll('.', '\\.')}" Version="([^"]+)"`))?.[1];
  assert.ok(value, `Missing dependency ${name}`);
  return value;
};

export function aliasConfiguration(configuration) {
  assert.equal(configuration.declarationCatalog, true);
  return { ...configuration, compilerLib: { ...configuration.compilerLib, module: packageId } };
}

export function aliasExtensions(source) {
  assert.ok(source.includes('module Fable.Core.TSExtensions'));
  return source.replaceAll('Fable.Core.TSExtensions', `${packageId}Extensions`)
    .replaceAll('Fable.Core.TS', packageId)
    .replace('open Fable.Core.JsInterop', 'open Fable.Core\nopen Fable.Core.JsInterop');
}

